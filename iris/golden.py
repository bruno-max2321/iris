"""Golden references: a frozen analysis that `iris selftest --golden` re-runs and diffs.

<name>/golden.json holds the facts a correct pipeline must reproduce (frame counts, cuts, events, camera
classes, light labels, background colour, caption text, loudness, transcript size) and where the video
comes from: a synthetic fixture (regenerated by tools/make_fixtures.sh) or a real reference identified by
its sha256, found in the workspace (its media is never committed).

Goldens are machine-specific: another ffmpeg renders the synthetic fixtures with other bytes, and a real
reference only exists in one workspace. `freeze` writes to <workspace>/golden/ (never committed); the
goldens under fixtures/golden/ were frozen on the development machine. A check reads both, and a
workspace golden replaces a repository golden of the same name. A fixture whose bytes differ from the
frozen ones is skipped with the advice to run `iris selftest --freeze-fixtures` on this machine.

A check ingests the source into a throwaway workspace, analyzes it, and compares fact by fact:
labels and counts exactly, numbers within the tolerance declared below, caption text by similarity.
Facts from a stage whose backend differs from the frozen one (another OCR engine, another Whisper
model) are skipped and reported, not failed. A golden whose source is not available is skipped."""

from __future__ import annotations

import difflib
import json
import shutil
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import __version__, analyze, ingest, paths
from .store import sha256_file

SCHEMA_VERSION = "1.0.0"
GOLDEN_DIR = paths.REPO_ROOT / "fixtures" / "golden"
LOCAL_DIR = "golden"  # under the workspace
TOLERANCE = {  # absolute, unless the key is in RELATIVE
    "shots.cut_times_s": 0.05, "montage.cuts_per_s": 0.05, "color.background_lab": 3.0,
    "audio.integrated_lufs": 0.5, "audio.true_peak_dbtp": 0.5, "audio.transcript_words": 0.1, "index.nominal_fps": 0.01,
}
RELATIVE = {"audio.transcript_words"}
TEXT_MIN_RATIO = 0.9
STAGE_OF = {"text.": "text", "audio.transcript": "transcript"}


def _read(p: Path) -> dict[str, Any]:
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def facts(ref_dir: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    """(facts, backends) from a reference's stage outputs."""
    idx, cov, sh, ev = _read(ref_dir / "index.json"), _read(ref_dir / "coverage.json"), _read(ref_dir / "shots.json"), _read(ref_dir / "events.json")
    mo, co, tx, au = _read(ref_dir / "motion.json"), _read(ref_dir / "color.json"), _read(ref_dir / "text.json"), _read(ref_dir / "audio.json")
    shots = sh.get("shots") or []
    color = {c["shot_id"]: c for c in co.get("shots") or []}
    motion = {m["shot_id"]: m for m in mo.get("shots") or []}
    f: dict[str, Any] = {
        "index.frame_count": idx.get("frame_count"), "index.vfr": idx.get("vfr"), "index.nominal_fps": idx.get("nominal_fps"),
        "coverage.decode": cov.get("decode"), "coverage.measurement": cov.get("measurement"),
        "shots.count": len(shots), "shots.cut_times_s": [round(float(s["t_in"]), 3) for s in shots[1:]],
        "shots.transition_in": [s.get("transition_in") for s in shots],
        "montage.cuts_per_s": ((sh.get("montage") or {}).get("cuts_per_s") or {}).get("overall"),
        "events": sorted(f"{e['type']}@{e['frame_first']}+{e['length_frames']}" for e in ev.get("events") or []),
        "motion.class": [(motion.get(s["shot_id"]) or {}).get("class") for s in shots],
        "light.key": [((color.get(s["shot_id"]) or {}).get("light") or {}).get("key") for s in shots],
        "light.side": [((color.get(s["shot_id"]) or {}).get("light") or {}).get("side") for s in shots],
        "light.edge": [((color.get(s["shot_id"]) or {}).get("light") or {}).get("edge") for s in shots],
        "color.background_lab": [((((color.get(s["shot_id"]) or {}).get("regions") or {}).get("background") or {}).get("lab_mean")) for s in shots],
        "text.status": tx.get("status"),
        "audio.status": au.get("status"),
    }
    if tx.get("status") == "ok":
        f["text.blocks"] = [b.get("text") for b in tx.get("blocks") or []]
        f["text.block_frames"] = [[b.get("frame_first_seen"), b.get("frame_last_seen")] for b in tx.get("blocks") or []]
    if au.get("status") == "ok":
        f["audio.integrated_lufs"] = (au.get("loudness") or {}).get("integrated_lufs")
        f["audio.true_peak_dbtp"] = (au.get("loudness") or {}).get("true_peak_dbtp")
        tr = au.get("transcript") or {}
        if tr.get("status") == "ok":
            f["audio.transcript_words"] = tr.get("word_count")
    backends = {"text": tx.get("backend"), "transcript": ((au.get("transcript") or {}).get("model"))}
    return f, backends


def _close(a: Any, b: Any, tol: float, rel: bool) -> bool:
    if a is None or b is None:
        return a is b
    if isinstance(a, list) or isinstance(b, list):
        return isinstance(a, list) and isinstance(b, list) and len(a) == len(b) and all(_close(x, y, tol, rel) for x, y in zip(a, b))
    lim = tol * max(abs(float(a)), 1.0) if rel else tol
    return abs(float(a) - float(b)) <= lim + 1e-9


def compare(frozen: dict[str, Any], frozen_backends: dict[str, Any], got: dict[str, Any], got_backends: dict[str, Any]) -> dict[str, Any]:
    diffs, skipped, checked = [], [], 0
    for k, want in frozen.items():
        stage = next((v for p, v in STAGE_OF.items() if k.startswith(p)), None)
        if stage and k not in ("text.status",) and frozen_backends.get(stage) != got_backends.get(stage):
            skipped.append({"fact": k, "reason": f"{stage} backend differs: frozen {frozen_backends.get(stage)}, now {got_backends.get(stage)}"})
            continue
        have = got.get(k)
        checked += 1
        if k == "text.blocks":
            ok = isinstance(have, list) and len(have) == len(want) and all(
                difflib.SequenceMatcher(None, (x or "").lower(), (y or "").lower()).ratio() >= TEXT_MIN_RATIO for x, y in zip(want, have))
        elif k in TOLERANCE:
            ok = _close(want, have, TOLERANCE[k], k in RELATIVE)
        else:
            ok = want == have
        if not ok:
            diffs.append({"fact": k, "frozen": want, "now": have})
    return {"checked": checked, "diffs": diffs, "skipped_facts": skipped}


def _source_of(manifest: dict[str, Any]) -> dict[str, Any]:
    p = Path(manifest["stored_path"]).resolve()
    fx = (paths.REPO_ROOT / "fixtures").resolve()
    if fx in p.parents:
        return {"fixture": str(p.relative_to(fx)), "sha256": manifest["sha256"]}
    return {"sha256": manifest["sha256"], "asset_id": manifest["asset_id"], "rights": manifest.get("rights")}


def freeze(asset_id: str, name: str | None = None, workspace: Path | None = None, golden_dir: Path | None = None) -> dict[str, Any]:
    ws = workspace or paths.workspace_root()
    m = ingest.load_manifest(asset_id, ws)
    f, backends = facts(ws / "refs" / asset_id)
    if not f.get("shots.count"):
        raise ValueError(f"{asset_id} has no analysis to freeze")
    src = _source_of(m)
    name = name or (Path(src["fixture"]).stem if "fixture" in src else asset_id)
    doc = {"schema_version": SCHEMA_VERSION, "name": name, "frozen_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "iris_version": __version__, "pipeline_version": _read(ws / "refs" / asset_id / "coverage.json").get("pipeline_version"),
           "source": src, "backends": backends, "facts": f, "tolerance": TOLERANCE}
    out = (golden_dir or ws / LOCAL_DIR) / name / "golden.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return {"ok": True, "name": name, "path": str(out), "facts": len(f), "source": src}


def freeze_fixtures(workspace: Path | None = None, golden_dir: Path | None = None) -> dict[str, Any]:
    """Freeze this machine's goldens for every synthetic fixture a repository golden names."""
    ws = workspace or paths.workspace_root()
    frozen, skipped = [], []
    for gp in sorted(GOLDEN_DIR.glob("*/golden.json")):
        g = json.loads(gp.read_text(encoding="utf-8"))
        rel = (g.get("source") or {}).get("fixture")
        if not rel:
            continue
        src = paths.REPO_ROOT / "fixtures" / rel
        if not src.exists():
            skipped.append({"name": g["name"], "reason": f"fixture {rel} not generated (run tools/make_fixtures.sh)"})
            continue
        tmp = Path(tempfile.mkdtemp(prefix="iris-golden-"))
        try:
            aid = ingest.ingest(str(src), "own", workspace=tmp)["asset_id"]
            analyze.analyze(aid, workspace=tmp)
            r = freeze(aid, name=g["name"], workspace=tmp, golden_dir=golden_dir or ws / LOCAL_DIR)
            frozen.append({"name": r["name"], "path": r["path"], "facts": r["facts"]})
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    return {"ok": bool(frozen), "frozen": frozen, "skipped": skipped}


def _find_source(src: dict[str, Any], ws: Path) -> tuple[Path | None, str | None]:
    if "fixture" in src:
        p = paths.REPO_ROOT / "fixtures" / src["fixture"]
        if not p.exists():
            return None, f"fixture {src['fixture']} not generated (run tools/make_fixtures.sh)"
        return p, None
    for mp in (ws / "refs").glob("*/manifest.json"):
        m = _read(mp)
        if m.get("sha256") == src.get("sha256"):
            p = Path(m.get("stored_path") or "")
            if p.exists():
                return p, None
            return None, f"original of {m.get('asset_id')} is no longer stored (gc or moved)"
    return None, "reference not in this workspace"


def check(names: list[str] | None = None, workspace: Path | None = None, golden_dir: Path | None = None) -> dict[str, Any]:
    ws = workspace or paths.workspace_root()
    found: dict[str, Path] = {}
    for gdir in ([golden_dir] if golden_dir else [GOLDEN_DIR, ws / LOCAL_DIR]):  # a workspace golden replaces a repository one
        for p in gdir.glob("*/golden.json"):
            found[p.parent.name] = p
    goldens = [found[n] for n in sorted(found) if not names or n in names]
    results, skipped = [], []
    for gp in goldens:
        g = json.loads(gp.read_text(encoding="utf-8"))
        src_path, why = _find_source(g["source"], ws)
        if src_path is None:
            skipped.append({"name": g["name"], "reason": why})
            continue
        if g["source"].get("sha256") and sha256_file(src_path) != g["source"]["sha256"]:
            if "fixture" in g["source"]:
                skipped.append({"name": g["name"], "frozen_in": str(gp.parent.parent), "reason": "fixture bytes differ from the frozen ones "
                                "(rendered by another ffmpeg): run `iris selftest --freeze-fixtures` once on this machine"})
                continue
            results.append({"name": g["name"], "ok": False, "diffs": [{"fact": "source.sha256", "frozen": g["source"]["sha256"], "now": "differs"}]})
            continue
        tmp = Path(tempfile.mkdtemp(prefix="iris-golden-"))
        try:
            aid = ingest.ingest(str(src_path), g["source"].get("rights") or "own", workspace=tmp)["asset_id"]
            analyze.analyze(aid, workspace=tmp)
            got, got_backends = facts(tmp / "refs" / aid)
            cmp = compare(g["facts"], g.get("backends") or {}, got, got_backends)
            res = {"name": g["name"], "ok": not cmp["diffs"], **cmp}
            if cmp["diffs"]:  # keep what the re-analysis wrote, to see why it differs
                keep = ws / LOCAL_DIR / g["name"] / "last_failed_run"
                shutil.rmtree(keep, ignore_errors=True)
                keep.mkdir(parents=True)
                for p in (tmp / "refs" / aid).glob("*.json"):
                    shutil.copy2(p, keep / p.name)
                res["kept_run"] = str(keep)
            results.append(res)
        except Exception as exc:
            results.append({"name": g["name"], "ok": False, "error": f"{type(exc).__name__}: {exc}"})
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    failed = [r for r in results if not r["ok"]]
    return {"ok": not failed and len(results) > 0, "goldens": len(goldens), "checked": len(results), "passed": len(results) - len(failed), "failed": failed,
            "skipped": skipped, "results": results}
